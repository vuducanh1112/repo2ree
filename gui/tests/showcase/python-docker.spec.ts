import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { expect, test } from "../helpers/fixtures";
import {
  activateExperimentEnvironment,
  buildExperimentEnvironment,
  commandScript,
  crossCheckSbom,
  dockerBuildExperimentEnvironmentScript,
  EXPERIMENT_OUTPUT_FILE,
  generateSbom,
  generateScript,
  keepReeArchive,
  main,
  openFilesConsole,
  openPort,
  provideHbom,
  provideMetadata,
  provisionWorkbench,
  pythonHelloWorld,
  releaseWorkbench,
  runEvaluate,
  runExperiment,
  SBOM_ARTIFACT_PATH,
  saveActivateScript,
  sealRee,
  startReeCreation,
  uploadSource,
} from "../helpers/flow";
import { reproduceOffline } from "../helpers/offline";
import { narrate, narrated } from "./narration";

const PROJECT_DIR = "source";
const EXPERIMENT_ENVIRONMENT_PATH = `${PROJECT_DIR}/runtime.tar`;

test.describe("REE pipeline", () => {
  test("golden path: provision through seal and release on one workbench", async ({ page }) => {
    let archive = "";
    await test.step("provision workbench", async () => {
      await startReeCreation(page);
      const setup = page.getByRole("region", { name: "Set up the workbench" });
      await expect(setup).toBeVisible();
      await expect(setup.getByRole("button", { name: /Provision workbench/i })).toBeVisible();

      await narrate(
        page,
        setup,
        "Pick a lab and provision a workbench: a bench with its own Docker daemon",
      );
      await provisionWorkbench(page);
    });

    await test.step("upload source tarball", async () => {
      const clearSource = await uploadSource(page, pythonHelloWorld());

      await expect(clearSource).toBeVisible();
      await expect(page.getByText(/Configuration locked/)).toBeVisible();
      await expect(page.getByText("python-docker.tar.gz", { exact: true }).first()).toBeVisible();

      const snapshot = page.getByRole("region", { name: "Workspace Snapshot" });
      await expect(snapshot.getByText("Origin", { exact: true })).toBeVisible();
      await expect(snapshot.getByText("tarball", { exact: true })).toBeVisible();
      await expect(snapshot.getByText("Size", { exact: true })).toBeVisible();
      await expect(snapshot.getByText(/^swh:1:dir:/)).toBeVisible();
      await narrate(page, snapshot, "The uploaded source, identified by the SWHID of what landed");
    });

    await test.step("browse uploaded files in the REE tree", async () => {
      await openFilesConsole(page);

      const archiveNodeNames = [
        ...new Set(
          execFileSync("tar", ["-tzf", pythonHelloWorld()], { encoding: "utf8" })
            .split("\n")
            .map((entry) => entry.trim())
            .filter(Boolean)
            .map((entry) => entry.replace(/\/+$/, "").split("/").filter(Boolean).pop())
            .filter((name): name is string => Boolean(name)),
        ),
      ];
      await page.getByPlaceholder("Filter files…").fill("upstream");
      for (const nodeName of archiveNodeNames) {
        const escaped = nodeName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        await expect(
          page.getByRole("button", { name: new RegExp(`^(Folder )?${escaped}$`) }),
        ).toBeVisible();
      }
      await page.getByRole("button", { name: "Collapse files" }).click();
    });

    await test.step("provide metadata", async () => {
      await provideMetadata(page, {
        name: "ree-hello-world",
        version: "1.0.0",
        description: "A reusable execution environment for the Python hello world archive.",
      });

      await expect(page.getByPlaceholder("deepfold-protein-structure-prediction")).toHaveValue(
        "ree-hello-world",
      );
      await expect(page.getByPlaceholder("1.0.0")).toHaveValue("1.0.0");
      await expect(page.getByPlaceholder("REE for reproducible execution of...")).toHaveValue(
        "A reusable execution environment for the Python hello world archive.",
      );
    });

    await test.step("run evaluation", async () => {
      await runEvaluate(page);
      await expect(main(page).getByRole("button", { name: /Re-run Evaluate/ })).toBeVisible();
    });

    await test.step("generate a build script from the repository", async () => {
      await openPort(page, "Build Experiment Environment");
      await expect(
        main(page).getByRole("heading", { name: "Build Experiment Environment", exact: true }),
      ).toBeVisible();
      const { message, graph } = await generateScript(page);
      expect(message).toMatch(/Loaded a generated build script/);
      expect(message).toMatch(/2 alternatives were available/);
      expect(graph).toContain("build-experiment-environment-inference");
      expect(graph).toContain("single-project-root-dockerfile-v1");

      await expect(page.getByLabel("Build experiment environment script")).toContainText(
        /Generated by repo2ree/,
      );
      await expect(page.getByLabel("Build experiment environment script")).toContainText(
        /docker build/,
      );
      await narrate(
        page,
        page.getByLabel("Build experiment environment script"),
        "Script inference chose the project's Dockerfile over its requirements.txt",
      );
    });

    await test.step("build experiment environment", async () => {
      await buildExperimentEnvironment(
        page,
        dockerBuildExperimentEnvironmentScript(PROJECT_DIR, EXPERIMENT_ENVIRONMENT_PATH),
        EXPERIMENT_ENVIRONMENT_PATH,
      );

      await openPort(page, "Build Experiment Environment");
      await expect(main(page).getByRole("button", { name: /Re-build/ })).toBeVisible();
      await narrate(
        page,
        main(page),
        "The experiment environment: an image built on the bench's daemon, saved as a file",
      );
    });

    await test.step("provide hardware BOM", async () => {
      await provideHbom(page, "Intel Core i9-14900K");
      await expect(main(page).getByPlaceholder("Intel Core i9-14900K").first()).toHaveValue(
        "Intel Core i9-14900K",
      );
    });

    await test.step("generate SBOM", async () => {
      await generateSbom(page);
      await expect(main(page).getByText("SBOM ready", { exact: true }).first()).toBeVisible();
    });

    await test.step("cross-check SBOM against the scanned dependencies", async () => {
      await crossCheckSbom(page);
      await narrate(
        page,
        main(page),
        "The SBOM scanned from the image, checked against the declared dependencies",
      );
    });

    await test.step("generate the activate experiment environment script from the built image", async () => {
      await openPort(page, "Build Experiment Environment");
      const { graph, script } = await generateScript(page, /Generate from experiment environment/);
      expect(graph).toContain("activate-experiment-environment-inference");
      expect(script).toMatch(/docker load --input/);
      expect(script).toMatch(/exec docker run --rm -v "\$PWD:\$PWD" -w "\$PWD"/);
      expect(script).not.toMatch(/exit 64/);
      await saveActivateScript(page, script);
    });

    await test.step("test activation", async () => {
      await activateExperimentEnvironment(page);
      await expect(main(page).getByRole("button", { name: /Re-run/ })).toBeVisible();
      await narrate(
        page,
        main(page),
        "The activation enters the experiment environment and hands over",
      );
    });

    await test.step("run experiment", async () => {
      await runExperiment(page, {
        name: "python-hello",
        runScript: commandScript(`python ${PROJECT_DIR}/main.py`, EXPERIMENT_OUTPUT_FILE),
        expectedStdout: "Pandas Hello World",
        generateFirst: true,
      });
      await narrate(
        page,
        main(page),
        "The experiment's result, checked by the author's own verify script",
      );
    });

    await test.step("seal and download the REE", async () => {
      await sealRee(page);

      const downloadButton = page.getByRole("banner").getByRole("button", { name: /Download REE/ });
      await expect(downloadButton).toBeEnabled();
      await narrate(
        page,
        downloadButton,
        "Sealed: the REE downloads as one archive a reviewer can reproduce",
      );
      archive = await keepReeArchive(page);
      const bundle = readFileSync(archive);
      expect(bundle.includes("ree/results/python-hello/result.txt")).toBe(true);
      expect(bundle.includes(`ree/${SBOM_ARTIFACT_PATH}`)).toBe(true);
    });

    if (!narrated()) {
      await test.step("reproduce the sealed REE offline, without repo2ree", async () => {
        const output = await reproduceOffline(archive);
        expect(output).toContain("Reusing sealed experiment environment");
        expect(output).toContain("Pandas Hello World");
        expect(output).not.toContain("VERIFIED: fail");
        expect(output).toContain("VERIFIED: pass");
        expect(output).toContain("All steps completed.");
      });
    }

    await test.step("release workbench", async () => {
      await releaseWorkbench(page);
    });
  });
});
