from __future__ import annotations

from pathlib import Path

from scripts.no_comments import main, stripped


def test_comments_and_docstrings_go_and_pragmas_stay() -> None:
    source = (
        '"""A module."""\n'
        "\n"
        "import os  # the os\n"
        "\n"
        "\n"
        "# A banner.\n"
        "def run() -> str:\n"
        '    """Run it."""\n'
        "\n"
        "    value = os.sep  # type: ignore[attr-defined]  # why\n"
        "    return value  # noqa: S101 — because\n"
    )

    assert stripped(source) == (
        "import os\n"
        "\n"
        "\n"
        "def run() -> str:\n"
        "    value = os.sep  # type: ignore[attr-defined]\n"
        "    return value  # noqa: S101\n"
    )


def test_a_body_of_nothing_but_a_docstring_keeps_a_statement() -> None:
    source = 'class Refused(Exception):\n    """Refused."""\n\n\ndef hook() -> None:\n    """Nothing."""\n'

    assert stripped(source) == "class Refused(Exception):\n    pass\n\n\ndef hook() -> None:\n    ...\n"


def test_text_that_only_looks_like_a_comment_stays() -> None:
    source = 'SCRIPT = """\n# Generated by repo2ree.\nrun\n"""\nURL = "https://example.org/#top"\n'

    assert stripped(source) == source


def test_the_check_fails_on_a_comment_and_fix_removes_it(tmp_path: Path) -> None:
    path = tmp_path / "module.py"
    path.write_text("x = 1  # one\n")

    assert main([str(path)]) == 1
    assert main(["--fix", str(path)]) == 0
    assert path.read_text() == "x = 1\n"
    assert main([str(path)]) == 0
