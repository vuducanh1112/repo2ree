"""Fail-closed venv experiment scaffold.

The venv analogue of the Docker experiment scaffold: restore the packed venv,
run the author-supplied command with its ``bin`` on ``PATH``, capture output to
the experiment's reserved log (redirected so the command's exit status is the
verdict), and cat it back.
"""

from __future__ import annotations

from repo2ree_core.script_inference.models import (
    BindingKind,
    CandidateDependency,
    DecisionContext,
    ExperimentBinding,
    InferenceEvidence,
    RenderedScript,
    RuntimeContractBinding,
    ScriptTarget,
    VenvRuntimeContract,
)
from repo2ree_core.script_inference.renderers._scaffold import (
    candidate_examples_block,
    experiment_log_path,
    sh_quote,
    unconfigured_guard,
)
from repo2ree_core.script_inference.warnings import make_warning


def _bindings(context: DecisionContext) -> tuple[VenvRuntimeContract, str, ExperimentBinding]:
    contract_binding = context.binding("runtime_contract")
    experiment = context.binding("experiment")
    if not isinstance(contract_binding, RuntimeContractBinding) or not isinstance(
        contract_binding.contract, VenvRuntimeContract
    ):
        raise ValueError("venv_experiment_v1 renderer reached without a venv runtime_contract binding")
    if not isinstance(experiment, ExperimentBinding):
        raise ValueError("venv_experiment_v1 renderer reached without an experiment binding")
    return contract_binding.contract, contract_binding.provenance, experiment


class VenvExperimentRenderer:
    code = "venv_experiment_v1"
    requires: frozenset[BindingKind] = frozenset({"runtime_contract", "experiment"})

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        contract, provenance, experiment = _bindings(context)
        run_log = experiment_log_path(experiment.name)
        body = _render_body(
            artifact_path=contract.artifact_path,
            venv_restore_dir=contract.venv_restore_dir,
            run_log=run_log,
            examples=candidate_examples_block([], noun="experiment"),
        )
        dependencies = [
            CandidateDependency(
                kind="runtime_artifact",
                path=contract.artifact_path,
                digest=context.runtime.accessor.stat(contract.artifact_path).digest or "",
                role="runtime",
            ),
            CandidateDependency(
                kind="experiment_declaration",
                path=experiment.run_script_path,
                digest="",
                role="experiment",
            ),
        ]
        evidence = [
            InferenceEvidence(
                code="venv_runtime_contract",
                path=contract.artifact_path,
                detail=f"Packed venv runtime (provenance: {provenance}).",
            )
        ]
        warnings = [make_warning("execution_not_validated"), make_warning("experiment_command_missing")]
        if run_log not in experiment.output_paths:
            warnings.append(make_warning("experiment_output_declaration_missing", affected_paths=[run_log]))
        return RenderedScript(body=body, dependencies=dependencies, evidence=evidence, warnings=warnings)


def _render_body(*, artifact_path: str, venv_restore_dir: str, run_log: str, examples: str) -> str:
    guard = unconfigured_guard("Experiment", "Edit the 'set --' line in this script before running the experiment.")
    return f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: venv-runtime-experiment-v1
# The venv restore/run wrapper was inferred.
# The scientific experiment command was not selected automatically.

RUNTIME_ARTIFACT={sh_quote(artifact_path)}
VENV_DIR={sh_quote(venv_restore_dir)}
RUN_LOG={sh_quote(run_log)}

# REQUIRED: define the experiment command whose result you intend to preserve.
{examples}
set --

{guard}

# Restore the packed virtual environment to the absolute path it was built at.
rm -rf "$VENV_DIR"
mkdir -p "$(dirname "$VENV_DIR")"
tar -xzf "$RUNTIME_ARTIFACT" -C "$(dirname "$VENV_DIR")"

PATH="$VENV_DIR/bin:$PATH"
export PATH

mkdir -p "$(dirname "$RUN_LOG")"

# Redirect instead of piping through tee so the command's exit status remains
# the experiment verdict.
"$@" >"$RUN_LOG"

cat "$RUN_LOG"
"""
