"""Fail-closed test activation scaffold for a Docker experiment environment.

The command runs inside the activated experiment environment and is never selected
automatically: the author fills the ``set --`` line, with any image-declared commands
offered as commented examples.
"""

from __future__ import annotations

from repo2ree_core.author_recipes.inference.models import BindingKind, DecisionContext, RenderedScript
from repo2ree_core.author_recipes.inference.renderers._scaffold import (
    candidate_examples_block,
    unconfigured_guard,
)
from repo2ree_core.author_recipes.inference.warnings import make_warning
from repo2ree_protocol.command import ScriptTarget
from repo2ree_protocol.inference import (
    CandidateDependency,
    CommandCandidatesBinding,
    DockerExperimentEnvironmentContract,
    ExperimentEnvironmentContractBinding,
    InferenceEvidence,
)


def _docker_contract(context: DecisionContext) -> tuple[DockerExperimentEnvironmentContract, str]:
    binding = context.binding("experiment_environment_contract")
    if not isinstance(binding, ExperimentEnvironmentContractBinding) or not isinstance(
        binding.contract, DockerExperimentEnvironmentContract
    ):
        raise ValueError(
            "docker_activation_v1 renderer reached without a docker experiment_environment_contract binding"
        )
    return binding.contract, binding.provenance


class DockerActivationRenderer:
    code = "docker_activation_v1"
    requires: frozenset[BindingKind] = frozenset({"experiment_environment_contract", "command_candidates"})

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        contract, provenance = _docker_contract(context)
        candidates_binding = context.binding("command_candidates")
        candidates = candidates_binding.candidates if isinstance(candidates_binding, CommandCandidatesBinding) else []

        body = _render_body(
            examples=candidate_examples_block(candidates, noun="activation"),
        )
        dependencies = [
            CandidateDependency(
                kind="experiment_environment_artifact",
                path=contract.artifact_path,
                digest=context.experiment_environment.accessor.stat(contract.artifact_path).digest or "",
                role="experiment_environment",
            )
        ]
        evidence = [
            InferenceEvidence(
                code="docker_experiment_environment_contract",
                path=contract.artifact_path,
                detail=f"Docker experiment environment {contract.image_ref} (provenance: {provenance}).",
            )
        ]
        warnings = [make_warning("execution_not_validated"), make_warning("activation_command_missing")]
        return RenderedScript(body=body, dependencies=dependencies, evidence=evidence, warnings=warnings)


def _render_body(*, examples: str) -> str:
    guard = unconfigured_guard("Activation", "Edit the 'set --' line in this script before running activation.")
    return f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: docker-runtime-activation-v1
# Runs inside the activated experiment environment. The activation command was not inferred.
# Review and edit this script before running it.

# REQUIRED: define a finite command that proves the experiment environment is usable.
{examples}
set --

{guard}

"$@"
"""
