"""Shell renderer for the Slurm launch: each of the REE's scripts run as a Slurm job step, waited for.

What each script asks the cluster for is the author's to set; the rendered values are starting points, with
the time limit kept within the default partition's when the probe reported one. A cluster's own options
(partition, account) are left to whoever runs the REE, through ``REE_LAUNCH_OPTIONS``.
"""

from __future__ import annotations

import re

from repo2ree_core.author_recipes.inference.models import BindingKind, DecisionContext, RenderedScript
from repo2ree_core.author_recipes.inference.renderers._common import sh_comment
from repo2ree_protocol.command import ScriptTarget
from repo2ree_protocol.inference import InferenceEvidence, SlurmPartition

SLURM_LAUNCH_RENDERER = "slurm_launch"
# The time a script asks for when the default partition allows it.
DEFAULT_MINUTES = 30
_LIMIT = re.compile(r"^(?:(\d+)-)?(\d+)(?::(\d+))?(?::(\d+))?$")


def limit_minutes(limit: str | None) -> int | None:
    """A Slurm time limit in whole minutes; None when there is none (``infinite``) or it cannot be read.

    Slurm prints ``minutes``, ``minutes:seconds``, ``hours:minutes:seconds``, ``days-hours``,
    ``days-hours:minutes`` or ``days-hours:minutes:seconds``.
    """
    found = _LIMIT.match((limit or "").strip())
    if found is None:
        return None
    days, first, second, third = found.groups()
    if days is not None:
        hours, minutes = int(first), int(second or 0)
        return int(days) * 24 * 60 + hours * 60 + minutes
    if third is not None:
        return int(first) * 60 + int(second)
    return int(first)


def _clock(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}:00"


def _default_partition(partitions: list[SlurmPartition]) -> SlurmPartition | None:
    return next((partition for partition in partitions if partition.default), None)


class SlurmLaunchRenderer:
    code = SLURM_LAUNCH_RENDERER
    requires: frozenset[BindingKind] = frozenset()

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        probe = context.machine.slurm.probe()
        partition = _default_partition(probe.partitions)
        allowed = limit_minutes(partition.time_limit) if partition else None
        minutes = min(DEFAULT_MINUTES, allowed) if allowed else DEFAULT_MINUTES
        seen = (
            f"Default partition {sh_comment(partition.name)}, time limit {sh_comment(partition.time_limit or '')}"
            if partition
            else "No default partition reported"
        )
        body = f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: slurm-job-step-launch
# Evidence:
#   Slurm answers where this REE's scripts run
#   {seen}
#
# Runs each of the REE's scripts as a Slurm job step and waits for it: the workbench and run.sh call
# `sh launch.sh <command>` for every script. The values below are starting points: set what the experiment
# needs. A cluster's own options (partition, account, QOS) belong to whoever runs it, through REE_LAUNCH_OPTIONS.
CPUS=1
TIME_LIMIT={_clock(minutes)}
# Leave empty for the cluster's default memory, and for no GPUs.
MEMORY=
GPUS=

# One task on one node: the command runs once. REE_LAUNCH_OPTIONS comes last, so a reproducer's options win.
# shellcheck disable=SC2086
exec srun --nodes=1 --ntasks=1 --cpus-per-task="$CPUS" --time="$TIME_LIMIT" \\
  ${{MEMORY:+--mem="$MEMORY"}} ${{GPUS:+--gpus="$GPUS"}} ${{REE_LAUNCH_OPTIONS:-}} "$@"
"""
        evidence = [InferenceEvidence(code="slurm_usable", detail=f"srun at {probe.srun_path or 'unknown'}")]
        if partition is not None:
            evidence.append(
                InferenceEvidence(
                    code="slurm_default_partition",
                    detail=f"{partition.name}, time limit {partition.time_limit or 'not reported'}",
                )
            )
        return RenderedScript(body=body, evidence=evidence)
