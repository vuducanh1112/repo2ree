"""Fail-closed experiment run scaffold for a Docker experiment environment.

The command runs inside the activated experiment environment and is never selected
automatically: the author fills the ``set --`` line, and its stdout goes to the run log.
"""

from __future__ import annotations

from repo2ree_core.author_recipes.inference.models import BindingKind, DecisionContext, RenderedScript
from repo2ree_core.author_recipes.inference.renderers._scaffold import (
    candidate_examples_block,
    experiment_log_path,
    sh_quote,
    unconfigured_guard,
)
from repo2ree_core.author_recipes.inference.warnings import make_warning
from repo2ree_protocol.command import ScriptTarget
from repo2ree_protocol.inference import (
    CandidateDependency,
    CommandCandidatesBinding,
    DockerExperimentEnvironmentContract,
    ExperimentBinding,
    ExperimentEnvironmentContractBinding,
    InferenceEvidence,
)


def _bindings(context: DecisionContext) -> tuple[DockerExperimentEnvironmentContract, str, ExperimentBinding]:
    contract_binding = context.binding("experiment_environment_contract")
    experiment = context.binding("experiment")
    if not isinstance(contract_binding, ExperimentEnvironmentContractBinding) or not isinstance(
        contract_binding.contract, DockerExperimentEnvironmentContract
    ):
        raise ValueError(
            "docker_experiment_v1 renderer reached without a docker experiment_environment_contract binding"
        )
    if not isinstance(experiment, ExperimentBinding):
        raise ValueError("docker_experiment_v1 renderer reached without an experiment binding")
    return contract_binding.contract, contract_binding.provenance, experiment


class DockerExperimentRenderer:
    code = "docker_experiment_v1"
    requires: frozenset[BindingKind] = frozenset(
        {"experiment_environment_contract", "command_candidates", "experiment"}
    )

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        contract, provenance, experiment = _bindings(context)
        candidates_binding = context.binding("command_candidates")
        candidates = candidates_binding.candidates if isinstance(candidates_binding, CommandCandidatesBinding) else []
        run_log = experiment_log_path(experiment.name)

        body = _render_body(
            run_log=run_log,
            examples=candidate_examples_block(candidates, noun="experiment"),
        )
        dependencies = [
            CandidateDependency(
                kind="experiment_environment_artifact",
                path=contract.artifact_path,
                digest=context.experiment_environment.accessor.stat(contract.artifact_path).digest or "",
                role="experiment_environment",
            ),
            CandidateDependency(
                kind="experiment_declaration",
                path=experiment.run_script_path,
                digest="",
                role="experiment",
            ),
        ]
        evidence = [
            InferenceEvidence(
                code="docker_experiment_environment_contract",
                path=contract.artifact_path,
                detail=f"Docker experiment environment {contract.image_ref} (provenance: {provenance}).",
            )
        ]
        warnings = [make_warning("execution_not_validated"), make_warning("experiment_command_missing")]
        if run_log not in experiment.output_paths:
            warnings.append(make_warning("experiment_output_declaration_missing", affected_paths=[run_log]))
        return RenderedScript(body=body, dependencies=dependencies, evidence=evidence, warnings=warnings)


def _render_body(*, run_log: str, examples: str) -> str:
    guard = unconfigured_guard("Experiment", "Edit the 'set --' line in this script before running the experiment.")
    return f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: docker-runtime-experiment-v1
# Runs inside the activated experiment environment.
# The scientific experiment command was not selected automatically.

RUN_LOG={sh_quote(run_log)}

# REQUIRED: define the experiment command whose result you intend to preserve.
{examples}
set --

{guard}

mkdir -p "$(dirname "$RUN_LOG")"
"$@" >"$RUN_LOG"
cat "$RUN_LOG"
"""
