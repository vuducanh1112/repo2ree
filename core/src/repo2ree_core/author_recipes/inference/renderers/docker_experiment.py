"""Fail-closed Docker experiment scaffold.

Like the Docker activation scaffold, but the run captures output to the
experiment's reserved log path (redirected, not piped, so the container's exit
status stays the experiment verdict) and cats it back. The scientific command is
never inferred in Phase 1; image-declared commands are commented suggestions.
"""

from __future__ import annotations

from repo2ree_core.author_recipes.inference.models import (
    BindingKind,
    CandidateDependency,
    CommandCandidatesBinding,
    DecisionContext,
    DockerRuntimeContract,
    ExperimentBinding,
    InferenceEvidence,
    RenderedScript,
    RuntimeContractBinding,
    ScriptTarget,
)
from repo2ree_core.author_recipes.inference.renderers._scaffold import (
    candidate_examples_block,
    experiment_log_path,
    sh_quote,
    unconfigured_guard,
)
from repo2ree_core.author_recipes.inference.warnings import make_warning


def _bindings(context: DecisionContext) -> tuple[DockerRuntimeContract, str, ExperimentBinding]:
    contract_binding = context.binding("runtime_contract")
    experiment = context.binding("experiment")
    if not isinstance(contract_binding, RuntimeContractBinding) or not isinstance(
        contract_binding.contract, DockerRuntimeContract
    ):
        raise ValueError("docker_experiment_v1 renderer reached without a docker runtime_contract binding")
    if not isinstance(experiment, ExperimentBinding):
        raise ValueError("docker_experiment_v1 renderer reached without an experiment binding")
    return contract_binding.contract, contract_binding.provenance, experiment


class DockerExperimentRenderer:
    code = "docker_experiment_v1"
    requires: frozenset[BindingKind] = frozenset({"runtime_contract", "command_candidates", "experiment"})

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        contract, provenance, experiment = _bindings(context)
        candidates_binding = context.binding("command_candidates")
        candidates = candidates_binding.candidates if isinstance(candidates_binding, CommandCandidatesBinding) else []
        run_log = experiment_log_path(experiment.name)

        body = _render_body(
            artifact_path=contract.artifact_path,
            image_ref=contract.image_ref,
            workspace_mount=contract.workspace_mount,
            working_directory=contract.working_directory,
            run_log=run_log,
            examples=candidate_examples_block(candidates, noun="experiment"),
        )
        dependencies = [
            CandidateDependency(
                kind="runtime_artifact",
                path=contract.artifact_path,
                digest=context.runtime.accessor.stat(contract.artifact_path).digest or "",
                role="runtime",
            ),
            CandidateDependency(
                kind="experiment_declaration",
                path=experiment.run_script_path,
                digest="",
                role="experiment",
            ),
        ]
        evidence = [
            InferenceEvidence(
                code="docker_runtime_contract",
                path=contract.artifact_path,
                detail=f"Docker runtime {contract.image_ref} (provenance: {provenance}).",
            )
        ]
        warnings = [make_warning("execution_not_validated"), make_warning("experiment_command_missing")]
        if run_log not in experiment.output_paths:
            warnings.append(make_warning("experiment_output_declaration_missing", affected_paths=[run_log]))
        return RenderedScript(body=body, dependencies=dependencies, evidence=evidence, warnings=warnings)


def _render_body(
    *,
    artifact_path: str,
    image_ref: str,
    workspace_mount: str,
    working_directory: str,
    run_log: str,
    examples: str,
) -> str:
    guard = unconfigured_guard("Experiment", "Edit the 'set --' line in this script before running the experiment.")
    return f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: docker-runtime-experiment-v1
# The Docker/runtime plumbing was inferred.
# The scientific experiment command was not selected automatically.

RUNTIME_ARTIFACT={sh_quote(artifact_path)}
IMAGE_TAG={sh_quote(image_ref)}
RUN_LOG={sh_quote(run_log)}

# REQUIRED: define the experiment command whose result you intend to preserve.
{examples}
set --

{guard}

docker load --input "$RUNTIME_ARTIFACT"

mkdir -p "$(dirname "$RUN_LOG")"

# Redirect instead of piping through tee so the container's exit status remains
# the experiment verdict.
docker run --rm \\
    -v "$(pwd):{workspace_mount}" \\
    -w {sh_quote(working_directory)} \\
    "$IMAGE_TAG" \\
    "$@" \\
    >"$RUN_LOG"

cat "$RUN_LOG"
"""
