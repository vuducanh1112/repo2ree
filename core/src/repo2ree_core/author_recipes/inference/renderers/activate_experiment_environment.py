"""The activate experiment environment script, inferred whole from the experiment environment contract.

Entering an experiment environment is mechanical once its kind is known, so these
render a complete script: no command to fill, no guard. It runs the command it is
given inside the experiment environment, from the workspace root.
"""

from __future__ import annotations

from repo2ree_core.author_recipes.inference.models import BindingKind, DecisionContext, RenderedScript
from repo2ree_core.author_recipes.inference.renderers._scaffold import sh_quote
from repo2ree_core.author_recipes.inference.warnings import make_warning
from repo2ree_protocol.command import ScriptTarget
from repo2ree_protocol.inference import (
    CandidateDependency,
    DockerExperimentEnvironmentContract,
    ExperimentEnvironmentContractBinding,
    InferenceEvidence,
    VenvExperimentEnvironmentContract,
)


def _docker_contract(context: DecisionContext) -> tuple[DockerExperimentEnvironmentContract, str]:
    binding = context.binding("experiment_environment_contract")
    if not isinstance(binding, ExperimentEnvironmentContractBinding) or not isinstance(
        binding.contract, DockerExperimentEnvironmentContract
    ):
        raise ValueError("renderer reached without a docker experiment_environment_contract binding")
    return binding.contract, binding.provenance


def _venv_contract(context: DecisionContext) -> tuple[VenvExperimentEnvironmentContract, str]:
    binding = context.binding("experiment_environment_contract")
    if not isinstance(binding, ExperimentEnvironmentContractBinding) or not isinstance(
        binding.contract, VenvExperimentEnvironmentContract
    ):
        raise ValueError("renderer reached without a venv experiment_environment_contract binding")
    return binding.contract, binding.provenance


def _dependency(context: DecisionContext, artifact_path: str) -> CandidateDependency:
    return CandidateDependency(
        kind="experiment_environment_artifact",
        path=artifact_path,
        digest=context.experiment_environment.accessor.stat(artifact_path).digest or "",
        role="experiment_environment",
    )


class DockerActivateExperimentEnvironmentRenderer:
    code = "docker_activate_experiment_environment_v1"
    requires: frozenset[BindingKind] = frozenset({"experiment_environment_contract"})

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        contract, provenance = _docker_contract(context)
        body = f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: docker-activate-experiment-environment-v1

EXPERIMENT_ENVIRONMENT_ARTIFACT={sh_quote(contract.artifact_path)}
IMAGE_TAG={sh_quote(contract.image_ref)}

docker image inspect "$IMAGE_TAG" >/dev/null 2>&1 || docker load --input "$EXPERIMENT_ENVIRONMENT_ARTIFACT"
exec docker run --rm -v "$PWD:$PWD" -w "$PWD" --entrypoint "" "$IMAGE_TAG" "$@"
"""
        evidence = [
            InferenceEvidence(
                code="docker_experiment_environment_contract",
                path=contract.artifact_path,
                detail=f"Docker experiment environment {contract.image_ref} (provenance: {provenance}).",
            )
        ]
        return RenderedScript(
            body=body,
            dependencies=[_dependency(context, contract.artifact_path)],
            evidence=evidence,
            warnings=[make_warning("execution_not_validated")],
        )


