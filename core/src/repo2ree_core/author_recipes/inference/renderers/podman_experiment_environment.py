"""Shell renderer for the Podman build strategy: the project's one container file built with Podman.

The sibling of the Docker build renderer: the same container file, build context and declared artifact, built
with ``podman build`` and saved with ``podman save`` as a docker-archive, the format the activation's archive
inspection reads and either engine loads.
"""

from __future__ import annotations

from repo2ree_core.author_recipes.inference.models import BindingKind, DecisionContext, RenderedScript
from repo2ree_core.author_recipes.inference.renderers._common import (
    DOCKER_EXPERIMENT_ENVIRONMENT_ARTIFACT_SUFFIX,
    build_experiment_environment_artifact_path,
    podman_image_ref,
    sh_comment,
    sh_quote,
)
from repo2ree_core.author_recipes.inference.renderers.docker_experiment_environment import _bindings
from repo2ree_core.author_recipes.inference.warnings import make_warning
from repo2ree_protocol.command import ScriptTarget
from repo2ree_protocol.inference import CandidateDependency, InferenceEvidence

PODMAN_BUILD_RENDERER = "podman_build"


class PodmanBuildRenderer:
    code = PODMAN_BUILD_RENDERER
    requires: frozenset[BindingKind] = frozenset({"project_root", "dockerfile"})

    def render(self, context: DecisionContext, target: ScriptTarget) -> RenderedScript:
        root, dockerfile = _bindings(context)
        artifact = build_experiment_environment_artifact_path(
            context.experiment_environment.declared_experiment_environment_path,
            root.path,
            DOCKER_EXPERIMENT_ENVIRONMENT_ARTIFACT_SUFFIX,
        )
        body = f"""#!/usr/bin/env sh
set -eu

# Generated by repo2ree.
#
# Inference rule: single-project-root-containerfile-podman
# Evidence:
#   Container file {sh_comment(dockerfile.digest)}
#   Logical project root: {sh_comment(root.path)}
#   Exactly one container file at the logical project root
#   Podman usable where this REE's scripts run
#
# This script has been inferred but not yet validated by execution.

CONTAINERFILE={sh_quote(dockerfile.path)}
BUILD_CONTEXT={sh_quote(dockerfile.build_context)}
IMAGE_TAG={sh_quote(podman_image_ref(context.ree_name))}
EXPERIMENT_ENVIRONMENT_ARTIFACT={sh_quote(artifact)}

podman build \\
    --file "$CONTAINERFILE" \\
    --tag "$IMAGE_TAG" \\
    "$BUILD_CONTEXT"

mkdir -p "$(dirname "$EXPERIMENT_ENVIRONMENT_ARTIFACT")"
rm -f "$EXPERIMENT_ENVIRONMENT_ARTIFACT"
podman save \\
    --format docker-archive \\
    --output "$EXPERIMENT_ENVIRONMENT_ARTIFACT" \\
    "$IMAGE_TAG"
"""
        return RenderedScript(
            body=body,
            dependencies=[
                CandidateDependency(kind="source", path=dockerfile.path, digest=dockerfile.digest, role="dockerfile"),
                CandidateDependency(
                    kind="experiment_environment_declaration", path=artifact, digest="", role="experiment_environment"
                ),
            ],
            evidence=[
                InferenceEvidence(
                    code="single_project_root_dockerfile",
                    path=dockerfile.path,
                    digest=dockerfile.digest,
                    detail="Exactly one container file at the logical project root; build context is that root.",
                )
            ],
            warnings=[make_warning("execution_not_validated")],
        )
